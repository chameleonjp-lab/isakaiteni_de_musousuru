function conversationDeath(person, choice, repeated = false) {
  if (repeated) {
    return {
      heading: "同じ行動を怪しまれた",
      body: `${person.name}にもう一度「${choice.label}」と返した。${repeatedReplyDeaths[person.id]}`
    };
  }
  const index = characterReplies[person.id]?.indexOf(choice.label);
  const [heading, body] = sceneReplyDeaths[choice.key] ?? characterDeaths[person.id][index];
  return { heading, body };
}

