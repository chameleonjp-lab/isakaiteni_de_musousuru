function talkChoices(key, correct, replies, fatal = null, allFatal = false) {
  const wrong = fatal ?? [replies[0], replies[1]];
  const values = [
    { key: key + ".correct", label: correct, outcome: "correct" },
    { key: key + ".danger1", label: wrong[0], outcome: "death" },
    { key: key + ".danger2", label: wrong[1], outcome: "death" },
    { key: key + (allFatal ? ".danger3" : ".neutral"), label: replies[2], outcome: allFatal ? "death" : "neutral" }
  ];
  const offset = [...key].reduce((sum, letter) => sum + letter.charCodeAt(0), 0) % values.length;
  return values.slice(offset).concat(values.slice(0, offset));
}

